// Regenerates types/database.types.ts from the local database.
//
// `supabase gen types` writes to stdout; this captures it, prepends the
// do-not-edit header, and writes the file — so `npm run db:types` and the CI
// staleness check produce byte-identical output and a plain `git diff` is the
// whole comparison.
//
// Uses only Node built-ins on purpose: the schema-drift CI job runs it without
// `npm ci`. The CLI resolves to the pinned devDependency when installed, and
// otherwise to the `supabase` on PATH (CI's setup-cli, which reads the same
// pinned version from package.json).

import { spawnSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'types/database.types.ts';
const HEADER = `// GENERATED by \`npm run db:types\` — DO NOT HAND-EDIT.
// Source of truth: supabase/migrations/*.sql. Change a migration, then
// regenerate. CI fails when this file is stale.
// Import from '@/types/database', never from this path directly.

`;

const isWindows = process.platform === 'win32';
const local = join(
  'node_modules',
  '.bin',
  isWindows ? 'supabase.cmd' : 'supabase',
);
const cli = existsSync(local) ? local : 'supabase';

const result = spawnSync(cli, ['gen', 'types', 'typescript', '--local'], {
  encoding: 'utf8',
  shell: isWindows,
  maxBuffer: 32 * 1024 * 1024,
});

if (result.error || result.status !== 0 || result.stdout.trim() === '') {
  console.error(
    '\n  Could not generate database types.\n\n' +
      '  If the local stack is not running:\n\n' +
      '    npx supabase start      # requires Docker Desktop\n\n' +
      '  See workflow/01-local-setup.md.\n',
  );
  if (result.stderr) console.error(result.stderr);
  process.exit(1);
}

writeFileSync(OUT, HEADER + result.stdout);
console.log(`Wrote ${OUT}`);
